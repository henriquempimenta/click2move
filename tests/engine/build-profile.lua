local function staircase(count)
  local path, x, y = {}, 0, 0
  for index = 1, count do
    path[index] = point(x, y)
    x = x + 1
    if index % 2 == 0 then y = y + 1 end
  end
  return path
end
local function winding(count)
  local path, x, y = {}, 0, 0
  for index = 1, count do
    path[index] = point(x, y)
    local step = (index - 1) % 16
    if step < 6 then x = x + 4
    elseif step < 8 then y = y + 4
    elseif step < 14 then x = x - 4
    else y = y + 4 end
  end
  return path
end
local function straight(count)
  local path = {}
  for index = 1, count do path[index] = point(index, 0) end
  return path
end
local function zigzag(count)
  local path = {}
  for index = 1, count do path[index] = point(index * 10, index % 2 * 10) end
  return path
end
