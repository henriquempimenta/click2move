script.on_init(function()
  storage.c2m_build_profile = {case = 1, trial = 0}
end)
script.on_event(defines.events.on_tick, function()
  local state = storage.c2m_build_profile
  local case = CASES[state.case]
  if not case then return end
  local timer = helpers.create_profiler()
  local plan = Trajectory.build(case[2], case[3])
  timer.stop()
  assert(plan.work_limit == Trajectory.WORK_LIMIT and plan.build_work >= 0
    and plan.build_work <= plan.work_limit, "trajectory exceeded its refinement budget")
  assert(#plan.path_distances == #case[2] and #plan.waypoint_s == #case[2]
    and #plan.segments > 0, "incomplete trajectory construction")
  local arcs, tightest = 0, math.huge
  for _, segment in ipairs(plan.segments) do
    if segment.radius then arcs = arcs + 1; tightest = math.min(tightest, segment.radius) end
  end
  if state.trial > 0 then
    local prefix = string.format("C2M_BUILD_PROFILE case=%s trial=%d nodes=%d pieces=%d arcs=%d radius=%.6f work=%d limit=%d attempts=%d total=",
      case[1], state.trial, #case[2], #plan.segments, arcs, tightest == math.huge and 0 or tightest,
      plan.build_work, plan.work_limit, plan.construction_attempts)
    log({"", prefix, timer})
  end
  state.trial = state.trial + 1
  if state.trial > TRIALS then state.case, state.trial = state.case + 1, 0 end
  if state.case > #CASES then
    print(string.format("C2M_NATIVE_BUILD_PROFILE_OK cases=%d trials=%d", #CASES, #CASES * TRIALS))
  end
end)
